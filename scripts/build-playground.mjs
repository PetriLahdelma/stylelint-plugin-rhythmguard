#!/usr/bin/env node
/**
 * Bundle the real rules for the browser playground (docs/index.html) into
 * docs/playground/rhythmguard.js. Stylelint is replaced by a small shim and
 * Node built-ins by no-op shims; everything else is the shipped code, so the
 * playground cannot drift from the plugin. A contract test rebuilds the bundle
 * and fails when the committed file is stale.
 */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const shims = path.join(root, 'scripts', 'playground');

const nodeBuiltins = {
  name: 'node-builtins',
  setup(pluginBuild) {
    const map = {
      child_process: 'childProcess',
      fs: 'fs',
      os: 'os',
      path: 'path',
    };
    pluginBuild.onResolve({ filter: /^(node:)?(fs|path|child_process|os)$/ }, (args) => ({
      namespace: 'node-shim',
      path: args.path.replace(/^node:/, ''),
    }));
    pluginBuild.onLoad({ filter: /.*/, namespace: 'node-shim' }, (args) => ({
      contents: `module.exports = require(${JSON.stringify(path.join(shims, 'node-shims.js'))}).${map[args.path]};`,
      loader: 'js',
      resolveDir: shims,
    }));
  },
};

export async function buildPlayground({ outfile = path.join(root, 'docs', 'playground', 'rhythmguard.js'), write = true } = {}) {
  return build({
    alias: { stylelint: path.join(shims, 'stylelint-shim.js') },
    banner: { js: '/* stylelint-plugin-rhythmguard browser bundle. Generated by scripts/build-playground.mjs; do not edit. */' },
    bundle: true,
    // The presets module resolves the community scales directory from __dirname;
    // the shimmed fs finds nothing there, which is the intended browser behaviour.
    define: { __dirname: '"/"', __filename: '"/bundle.js"', 'process.env.NODE_ENV': '"production"' },
    entryPoints: [path.join(shims, 'browser.js')],
    format: 'iife',
    globalName: 'Rhythmguard',
    inject: [path.join(shims, 'process-inject.mjs')],
    legalComments: 'none',
    loader: { '.css': 'text', '.json': 'json' },
    logLevel: 'silent',
    minify: true,
    outfile,
    platform: 'browser',
    plugins: [nodeBuiltins],
    target: ['es2020'],
    write,
  });
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await buildPlayground();
  const out = result.outputFiles ? result.outputFiles[0].path : path.join(root, 'docs', 'playground', 'rhythmguard.js');
  process.stdout.write(`wrote ${path.relative(root, out)}\n`);
}
