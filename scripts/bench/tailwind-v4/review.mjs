#!/usr/bin/env node
/**
 * Tailwind v4 apps: draw the hand-review sample from the results that
 * measure.mjs wrote, as pre-registered in benchmarks/tailwind-v4/README.md.
 * Seed 20261115, at most 3 findings per app, uniform within each app, amended
 * definition. Writes benchmarks/tailwind-v4/review.json with each finding's
 * source line and the element's other spacing classes; ratings are added to
 * that file by the raters (`agent`, then `blind` from a second rater who saw
 * only the rubric and the code, then `final`), and existing ratings survive a
 * re-run.
 *
 *   node scripts/bench/tailwind-v4/review.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const benchDir = path.resolve(__dirname, '..', '..', '..', 'benchmarks', 'tailwind-v4');
const SEED = 20261115;
const PER_APP = 3;

// mulberry32: small, seedable, the same draw on every machine.
function random(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle(list, next) {
  const out = [...list];
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(next() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

const reviewPath = path.join(benchDir, 'review.json');
const previous = fs.existsSync(reviewPath) ? JSON.parse(fs.readFileSync(reviewPath, 'utf8')) : [];
const ratings = new Map(previous.map((item) => [item.id, item]));
const next = random(SEED);
const apps = JSON.parse(fs.readFileSync(path.join(benchDir, 'apps.json'), 'utf8')).filter((app) => app.role === 'sample');
const items = [];
for (const app of apps) {
  const result = JSON.parse(fs.readFileSync(path.join(benchDir, 'results', `${app.name}.json`), 'utf8'));
  const eligible = result.findings.filter((f) => f.group === 'rhythm' && !f.copied && !f.onScale && f.amended);
  const appDir = path.join(benchDir, 'repos', app.name, app.app === '.' ? '' : app.app);
  for (const finding of shuffle(eligible, next).slice(0, PER_APP)) {
    const lines = fs.readFileSync(path.join(appDir, finding.file), 'utf8').split('\n');
    const id = `${app.name}:${finding.file}:${finding.line}:${finding.token}`;
    const kept = ratings.get(id) || {};
    items.push({
      id,
      app: app.name,
      url: `https://github.com/${app.repo}/blob/${app.commit}/${app.app === '.' ? '' : `${app.app}/`}${finding.file}#L${finding.line}`,
      token: finding.token,
      px: finding.px,
      nearest: finding.nearest,
      form: finding.form,
      source: lines.slice(Math.max(0, finding.line - 2), finding.line + 1).map((l) => l.trim()).join(' ⏎ ').slice(0, 400),
      agent: kept.agent || null,
      agentReason: kept.agentReason || null,
      blind: kept.blind || null,
      blindReason: kept.blindReason || null,
      final: kept.final || null,
    });
  }
}
fs.writeFileSync(reviewPath, `${JSON.stringify(items, null, 2)}\n`);

// The same sample as a table to read.
const cell = (text) => String(text ?? '').replace(/\|/g, '\\|');
const rows = items.map((item, index) => `| ${index + 1} | ${item.app} | [\`${cell(item.token)}\`](${item.url}) | ${item.px} (${item.nearest.join(' / ')}) | ${item.agent || ''} | ${item.blind || ''} | ${item.final || ''} | ${cell(item.final && item.final === item.blind && item.final !== item.agent ? item.blindReason : item.agentReason)} |`);
fs.writeFileSync(path.join(benchDir, 'REVIEW.md'), [
  '# Tailwind v4 apps: hand review',
  '',
  'Generated by `scripts/bench/tailwind-v4/review.mjs` from `review.json`. Ratings follow the rubric in [README.md](README.md#the-hand-review); only *drift* counts toward the pass mark. *Agent* rated first; *Blind* is a second rater who saw only the rubric and the code; *Final* resolves disagreements by checking the evidence each rater cited (amendment 3).',
  '',
  '| # | App | Class | px (nearest steps) | Agent | Blind | Final | Reason for the final rating |',
  '| ---: | --- | --- | --- | --- | --- | --- | --- |',
  ...rows,
  '',
].join('\n'));
console.log(`${items.length} findings drawn from ${new Set(items.map((i) => i.app)).size} apps.`);
